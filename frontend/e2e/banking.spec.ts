import { test, expect, type Page } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

async function open(page: Page, app: string) {
  await page.evaluate(async id => (await import('/src/store/useOSStore.ts' as string)).useOSStore.getState().openAppWorkspace(id),app);
  const window = page.locator(`.os-window[data-app="${app}"]`);
  await expect(window).toBeVisible();
  return window;
}
test('shared banking settles reviewed moves, persists history, and handles unavailable network data',async({page})=>{
  test.setTimeout(120000);
  page.setDefaultTimeout(15000);
  await page.route('**/api/**',route=>route.fulfill({status:503,contentType:'application/json',body:'{}'}));
  await page.route(/^https:\/\//,route=>route.abort());
  await page.goto('/');
  await page.getByRole('button',{name:'Sign In / Login Boot',exact:true}).click();
  await page.getByPlaceholder('e.g. CY-9021-PLAYER or admin').fill('admin');
  await page.getByRole('button',{name:'START LOGIN BOOT',exact:true}).click();
  await expect(page.locator('.desktop-wordmark strong')).toHaveText('MiraverseOSx');
  await page.evaluate(async()=>{const {useOSStore}=await import('/src/store/useOSStore.ts' as string);useOSStore.setState((s:any)=>({gameplay:{...s.gameplay,player:{...s.gameplay.player,credits:1000,bits:9,banking:undefined}}}));});
  const treasury=await open(page,'finance');
  await expect(treasury.getByRole('heading',{name:'Your money, in view.'})).toBeVisible({timeout:20000});
  await treasury.getByRole('button',{name:'Add to savings'}).click();
  await treasury.getByRole('textbox',{name:'Amount in credits'}).fill('250');
  await treasury.getByRole('textbox',{name:'Memo optional'}).fill('Rainy day reserve');
  await treasury.getByRole('button',{name:'Review transaction'}).click();
  await expect(treasury.getByRole('region',{name:'Review transaction'})).toContainText('250');
  await treasury.getByRole('button',{name:'Confirm transaction'}).click();
  await expect(treasury.getByRole('status')).toContainText('Transaction settled');
  await treasury.getByRole('button',{name:'Close',exact:true}).click();
  const browser=await open(page,'browser');
  const address=browser.getByRole('combobox',{name:'Search VerseNet or enter a web address'});
  await address.fill('bank.aure');await address.press('Enter');
  await expect(browser.getByRole('heading',{name:'Everyday banking.'})).toBeVisible({timeout:20000});
  await expect(browser.locator('.bank-balances')).toContainText('750');
  await expect(browser.locator('.bank-balances')).toContainText('250');
  await browser.getByRole('button',{name:'Send credits'}).click();
  await browser.getByLabel('Recipient',{exact:true}).selectOption('resident:aelita');
  await browser.getByRole('textbox',{name:'Amount in credits'}).fill('75');
  await browser.getByRole('textbox',{name:'Memo optional'}).fill('Shared supplies');
  await browser.getByRole('button',{name:'Review transaction'}).click();
  await expect(browser.getByRole('region',{name:'Review transaction'})).toContainText('Aelita Hopper');
  await browser.getByRole('button',{name:'Confirm transaction'}).click();
  await expect(browser.getByRole('status')).toContainText('Transaction settled');
  await browser.getByLabel('Transaction type').selectOption('withdraw');
  await browser.getByRole('textbox',{name:'Amount in credits'}).fill('50');
  await browser.getByRole('button',{name:'Review transaction'}).click();
  await browser.getByRole('button',{name:'Confirm transaction'}).click();
  await expect(browser.getByRole('status')).toContainText('Transaction settled');
  await browser.getByRole('textbox',{name:'Amount in credits'}).fill('999');
  await browser.getByRole('button',{name:'Review transaction'}).click();
  await expect(browser.getByRole('alert')).toContainText('Insufficient savings');
  await browser.getByRole('button',{name:'Activity',exact:true}).click();
  await expect(browser.locator('.bank-entry')).toHaveCount(3);
  await browser.getByRole('searchbox',{name:'Search transactions'}).fill('Shared supplies');
  await expect(browser.locator('.bank-entry')).toHaveCount(1);
  await browser.locator('.bank-entry').click();
  await expect(browser.getByRole('region',{name:'Transaction receipt'})).toContainText('Available balance after: 675');
  await page.reload();
  const reopened=await open(page,'finance');
  await expect(reopened.locator('.bank-balances')).toContainText('725',{timeout:20000});
  await expect(reopened.locator('.bank-balances')).toContainText('200');
  await reopened.getByRole('button',{name:'Activity',exact:true}).click();
  await expect(reopened.locator('.bank-entry')).toHaveCount(3);
  await reopened.getByRole('button',{name:'Network data',exact:true}).click();
  await expect(reopened.getByRole('status')).toContainText('Network data is unavailable');
  await expect(reopened.locator('.treasury-ledger')).not.toContainText('892,416');
  await reopened.getByRole('button',{name:'Overview',exact:true}).click();
  await mkdir('../output/previews',{recursive:true});
  await page.screenshot({path:'../output/previews/banking-overview.png'});
  await page.setViewportSize({width:560,height:920});
  await expect.poll(()=>reopened.locator('.bank-workspace').evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1);
  await expect.poll(()=>reopened.locator('.bank-balances').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(2);
  await page.screenshot({path:'../output/previews/banking-window.png'});
  await page.setViewportSize({width:390,height:844});
  await reopened.getByRole('button',{name:'Maximize',exact:true}).click();
  await expect.poll(()=>reopened.locator('.bank-workspace').evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1);
  await reopened.getByRole('button',{name:'Move money',exact:true}).click();
  await reopened.getByRole('button',{name:'Review transaction'}).scrollIntoViewIfNeeded();
  await expect(reopened.getByRole('button',{name:'Review transaction'})).toBeInViewport();
  await page.screenshot({path:'../output/previews/banking-narrow.png'});
});
