  await home.getByRole('button',{name:'Study Window desk'}).click();
  await home.getByRole('button',{name:'Begin quiet study'}).click();
  await expect(home.getByTestId('home-stamina')).toHaveText('35/100');
  await home.getByRole('button',{name:'Furnishings',exact:true}).click();
  await home.locator('.myhome-product').filter({has:page.getByRole('heading',{name:'Guest seating',exact:true})}).getByRole('button',{name:'Order & install'}).click();
  await expect(home.getByTestId('home-credits')).toHaveText('2,600 cr');
